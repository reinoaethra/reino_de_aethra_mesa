const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const app = fs.readFileSync(path.join(root, 'app.js'), 'utf8');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
assert(html.includes('v4.2.6'), 'release HTML is v4.2.1');
assert(app.includes("data-tool=\"setup-move\">Preparar posições · livre"), 'GM free placement tool is visible');
const start = app.indexOf('async function moveMapToken(');
const end = app.indexOf('\n  async function', start + 10);
const fn = app.slice(start, end);
assert(fn.includes('if(freePlacement){'), 'free placement branch exists');
assert(fn.includes("if(!isMaster()||!isMasterController())"), 'free placement is master/controller only');
assert(fn.includes("x+Math.max(1,Number(footprint.w)||1)>MAP_WIDTH||y+Math.max(1,Number(footprint.h)||1)>MAP_HEIGHT"), 'token footprint remains inside board');
