const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const app = fs.readFileSync(path.join(root, 'app.js'), 'utf8');
const css = fs.readFileSync(path.join(root, 'styles.css'), 'utf8');
const sql = fs.readFileSync(path.join(root, 'tests', 'fixtures', 'supabase-migration-v4.2.1.sql'), 'utf8');

assert(html.includes('v4.2.9'), 'HTML identifies the v4.2.7 release');
assert(html.includes('styles.css?v=4.2.9') && html.includes('app.js?v=4.2.9'), 'site assets use the v4.2.7 cache key');
assert(app.includes("const V423_DICE_SIDES=[4,6,8,10,12,20]"), 'supported dice include D4, D6, D8, D10, D12 and D20');
assert(app.includes('Math.max(1,Math.min(20,Math.floor(Number(count)||1)))'), 'number of dice is bounded from 1 to 20');
assert(app.includes('secureDie(sides)'), 'each die is generated using the cryptographic random dice helper');
assert(app.includes("kind:'dice-roll'"), 'public rolls are recorded as session notes');
assert(app.includes("visibility==='master'"), 'private/public visibility is handled');
assert(app.includes('aethra.v423.private-dice.'), 'private rolls are isolated by campaign and master account');
assert(app.includes('localStorage.setItem(v423PrivateDiceKey()'), 'private rolls are persisted locally and not published as events');
assert(app.includes('data-action="v423-apply-roll"'), 'the result can be applied manually');
assert(app.includes("effect==='healing'"), 'manual application supports healing');
assert(app.includes("!['damage','healing'].includes(effect)"), 'manual application validates damage and healing modes');
assert(app.includes('<option value="damage">Aplicar como dano</option>'), 'damage mode is available in the UI');
assert(app.includes("kind:'dice-application'"), 'manual applications are recorded in the campaign timeline');
assert(app.includes("['dice-roll','Rolagens universais']") && app.includes("['dice-application','Efeitos de dados']"), 'timeline can filter universal rolls and applications');
assert(app.includes("data-action=\"v423-open-dice\""), 'universal roller is available from campaign controls');
assert(app.includes("state.modal==='v423-dice'"), 'roller modal is wired to the render cycle');
assert(css.includes('.v423-dice-result') && css.includes('.v423-dice-total') && css.includes('.v423-dice-rolls'), 'roller has dedicated visual components');
assert(css.includes('@media(max-width:620px)') && css.includes('.v423-dice-result'), 'roller has a mobile layout');
assert(sql.includes("'session_note'"), 'existing master session_note event type is retained; no new SQL event type is required');
console.log('v4.2.7 universal dice: secure dice, formula modifiers, public/private visibility, timeline, manual HP effects and responsive UI approved.');
